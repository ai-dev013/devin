export function createEnemy(type: EnemyType, position: { x: number; y: number }): Enemy {
  const template = ENEMY_TEMPLATES[type];
  return {
    ...template,
    id: `${type}-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
    position,
    stats: { ...template.stats },
  };
}

export function getRandomEnemyForArea(areaLevel: number): EnemyType {
  const enemyPool: { type: EnemyType; minLevel: number; maxLevel: number }[] = [
    { type: 'slime', minLevel: 1, maxLevel: 5 },
    { type: 'wolf', minLevel: 2, maxLevel: 8 },
    { type: 'snake', minLevel: 3, maxLevel: 10 },
    { type: 'bird', minLevel: 3, maxLevel: 10 },
    { type: 'bear', minLevel: 5, maxLevel: 12 },
    { type: 'goblin', minLevel: 6, maxLevel: 15 },
    { type: 'skeleton', minLevel: 8, maxLevel: 20 },
  ];

  const availableEnemies = enemyPool.filter(
    (e) => areaLevel >= e.minLevel && areaLevel <= e.maxLevel
  );

  if (availableEnemies.length === 0) {
    return 'slime';
  }

  return availableEnemies[Math.floor(Math.random() * availableEnemies.length)].type;
}
