export function getItemById(id: string): Item | Weapon | Armor | undefined {
  return [...CONSUMABLE_ITEMS, ...WEAPONS, ...ARMORS, ...KEY_ITEMS].find(
    (item) => item.id === id
  );
}

export function getMagicById(id: string): Magic | undefined {
  return MAGIC_SPELLS.find((magic) => magic.id === id);
}
